/**
 * 确定性伪随机数（xorshift32）。
 *
 * 为什么值得单独一个文件：示例数据、首屏小样本、粒子场都要同一串数。
 * 复制三份的代价从来不是那十几行，而是三份迟早各自漂移——某天粒子场
 * 换了写法，截图对比就和示例数据对不上了，而改的人并不知道自己在动
 * 别处的基准。
 *
 * 输出落在 [0, 1)，逐位可复现：同一个种子在任何机器上给出同一串数。
 * 种子为 0 时退回 1，因为 xorshift 的 0 是不动点，会永远吐 0。
 */
export function xorshift32(seed: number): () => number {
  let x = seed >>> 0 || 1;
  return () => {
    x ^= x << 13;
    x >>>= 0;
    x ^= x >>> 17;
    x ^= x << 5;
    x >>>= 0;
    return x / 4294967296;
  };
}
